"""``tests/sdk-contract/visual-changes-vectors.json`` is the server's answer (#1545, V7).

The browser script that applies page changes is held to this file in its own
contract test; this one holds the file to the server. It is regenerated by
``python -m backend.scripts.generate_visual_vectors``, never written by hand,
so a validator edited without regenerating it fails here ("vectors stale"),
and a regenerated file that moved an answer then fails the script's test.

Needs no database and no ``.git``, so it runs in ``scripts/core_build.sh``'s
copy too.
"""

from __future__ import annotations

import json

import pytest

from backend.scripts import generate_visual_vectors as vectors

pytestmark = pytest.mark.unit


def test_the_vectors_are_current():
    committed = vectors.VECTORS_PATH.read_text(encoding="utf-8")
    assert committed == vectors.render(vectors.build_vectors()), (
        "vectors stale: run `python -m backend.scripts.generate_visual_vectors`"
    )


def test_the_check_command_agrees(capsys):
    assert vectors.main(["--check"]) == 0
    assert "is current" in capsys.readouterr().out


def test_every_verdict_is_the_one_the_corpus_was_written_for():
    data = json.loads(vectors.VECTORS_PATH.read_text(encoding="utf-8"))
    by_id = {case["id"]: case for case in data["changes"]}
    refused = {case_id for case_id, _, _ in vectors.REFUSED}
    accepted = {case_id for case_id, _ in vectors.ACCEPTED}
    assert set(by_id) == refused | accepted and not refused & accepted
    assert [i for i in sorted(refused) if by_id[i]["accepted"]] == []
    assert [i for i in sorted(accepted) if not by_id[i]["accepted"]] == []
    assert data["counts"] == {
        "changes": len(refused) + len(accepted),
        "accepted": len(accepted),
        "page_rules": len(vectors.PAGE_RULES),
    }
    rules = {case["id"]: case["matches"] for case in data["page_rules"]}
    assert rules == {case[0]: case[4] for case in vectors.PAGE_RULES}


def test_the_file_carries_the_limits_a_script_checks():
    data = json.loads(vectors.VECTORS_PATH.read_text(encoding="utf-8"))
    assert data["limits"] == {
        "changes": 100,
        "bytes": 65536,
        "selector": 512,
        "text": 2000,
        "attribute_value": 2048,
        "alt": 500,
        "styles": 20,
        "style_value": 200,
    }
    assert data["ops"] == [
        "set_text",
        "set_attribute",
        "set_image",
        "hide",
        "set_style",
    ]
    assert "position" not in data["allowed_style_properties"]
    assert data["format_version"] == 1
