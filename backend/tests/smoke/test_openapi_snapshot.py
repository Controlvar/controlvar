@pytest.fixture(scope="module")
def stable_snapshot() -> Dict[str, Any]:
    return load_snapshot(STABLE_SNAPSHOT)


@pytest.fixture(scope="module")
def full_snapshot() -> Dict[str, Any]:
    return load_snapshot(FULL_SNAPSHOT)


@pytest.fixture(scope="module")
def core_document() -> Dict[str, Any]:
    return dump_document("core")


def test_snapshots_are_well_formed(stable_snapshot, full_snapshot):
    for name, document in (("stable", stable_snapshot), ("full", full_snapshot)):
        assert document.get("openapi", "").startswith("3."), (
            f"{name}: not an OpenAPI 3 document"
        )
        assert document.get("paths"), f"{name}: no paths"
        assert "components" in document, f"{name}: no components (dump with --full)"
        for path, _method, operation in _operations(document):
            stability = operation.get("x-stability")
            assert stability in (None, BETA, "stable"), (
                f"{name}: {path} has x-stability={stability!r}; only 'beta' means anything"
            )


def test_core_api_matches_stable_snapshot(stable_snapshot, core_document):
    errors, notes = compare(stable_snapshot, core_document)
    _warn_all("openapi-v1.stable.json", notes)
    assert not errors, _report(
        "The core API changed under a stable path. A stable route may not "
        "change shape; add a new route (mark it x-stability: beta while it "
        "settles) or bump the API version. If the change is intended, "
        "regenerate with `make openapi` and say so in the pull request:",
        errors,
    )


def test_stable_snapshot_is_a_subset_of_the_full_snapshot(
    stable_snapshot, full_snapshot
):
    """Every core operation exists, unchanged, in the full document."""
    errors, _notes = compare(stable_snapshot, full_snapshot)
    assert not errors, _report(
        "openapi-v1.full.json is not a superset of openapi-v1.stable.json "
        "(regenerate both with `make openapi`):",
        errors,
    )


def test_module_paths_match_the_dashboard_fixture(stable_snapshot, full_snapshot):
    """``full - stable`` is exactly what the URL guard treats as a module's."""
    module_paths = set(full_snapshot["paths"]) - set(stable_snapshot["paths"])
    fixture = json.loads(MODULE_PATHS_FIXTURE.read_text(encoding="utf-8"))
    listed = set(fixture["paths"])
    assert module_paths == listed, (
        "frontend/src/tests/fixtures/openapi.module-paths.json disagrees with the "
        f"two snapshots.\n  only in the snapshots: {sorted(module_paths - listed)}"
        f"\n  only in the fixture: {sorted(listed - module_paths)}"
    )


@pytest.mark.modules
def test_full_api_matches_full_snapshot(full_snapshot):
    document = dump_document("full")
    errors, notes = compare(full_snapshot, document)
    _warn_all("openapi-v1.full.json", notes)
    assert not errors, _report(
        "The full-profile API changed under a stable path (see "
        "test_core_api_matches_stable_snapshot for the rule; regenerate with "
        "`make openapi` if intended):",
        errors,
    )


#: #580: each experiment stores these, and the results read them by default.
CORRECTION_SETTINGS = ("correction_method", "confidence_level")


@pytest.mark.regression
def test_the_snapshot_carries_the_stored_correction_settings(stable_snapshot):
    """Regenerating the snapshot proves only that it matches the code; this
    says what the code must contain. A field missing from ExperimentResponse
    would let a client read a default over the stored choice (#580)."""
    schemas = stable_snapshot["components"]["schemas"]
    for name in ("ExperimentCreate", "ExperimentUpdate", "ExperimentResponse"):
        properties = schemas[name]["properties"]
        assert set(CORRECTION_SETTINGS) <= set(properties), name
    created = schemas["ExperimentCreate"]["properties"]
    assert created["correction_method"]["default"] == "benjamini_hochberg"
    assert created["confidence_level"]["default"] == 0.95

    # The results routes take no fixed default: omitted means stored.
    for path in (
        "/api/v1/results/{experiment_id}",
        "/api/v1/results/{experiment_id}/sample-size",
    ):
        parameters = {
            p["name"]: p for p in stable_snapshot["paths"][path]["get"]["parameters"]
        }
        for name in CORRECTION_SETTINGS:
            assert parameters[name]["schema"].get("default") is None, (path, name)


#: #448: the sentence ``/tracking/assign``'s stable description gained.
BALANCED_ASSIGN_SENTENCE = (
    "For an experiment that balances within groups, a new user's variant also "
    "depends on the users of their group assigned before them."
)


@pytest.mark.regression
def test_the_snapshot_carries_balance_within_and_never_its_key(
    stable_snapshot, full_snapshot, core_document
):
    """#448: ``balance_within`` is on the create, update and response schemas;
    the experiment's block-order key, ``balance_seed``, is in neither snapshot
    nor in the live core document, whose schemas are what the routes answer
    with."""
    schemas = stable_snapshot["components"]["schemas"]
    for name in ("ExperimentCreate", "ExperimentUpdate", "ExperimentResponse"):
        assert "balance_within" in schemas[name]["properties"], name
    for name, document in (
        ("openapi-v1.stable.json", stable_snapshot),
        ("openapi-v1.full.json", full_snapshot),
        ("the live core document", core_document),
    ):
        text = json.dumps(document)
        assert "balance_within" in text, f"{name}: the positive control is missing"
        assert "balance_seed" not in text, f"balance_seed found in {name}"
    assign = stable_snapshot["paths"]["/api/v1/tracking/assign"]["post"]
    assert BALANCED_ASSIGN_SENTENCE in " ".join(assign["description"].split())


BALANCED_GROUPS_PATH = "/api/v1/results/{experiment_id}/balanced-groups"


def _referenced_schemas(document: Dict[str, Any], node: Any, seen=None) -> Dict:
    """Every component schema ``node`` references, transitively, by name."""
    seen = {} if seen is None else seen
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            name = ref.rsplit("/", 1)[-1]
            if name not in seen:
                seen[name] = document["components"]["schemas"][name]
                _referenced_schemas(document, seen[name], seen)
        for value in node.values():
            _referenced_schemas(document, value, seen)
    elif isinstance(node, list):
        for value in node:
            _referenced_schemas(document, value, seen)
    return seen


def test_the_balanced_groups_route_is_beta_and_carries_no_place_in_a_group(
    stable_snapshot, full_snapshot, core_document
):
    """#448: the balanced-groups route is in both snapshots, marked beta, as
    the live core document serves it (a beta route's change only warns in the
    comparison above, so this compares it exactly); and no document names a
    user's place in their group (``balance_seq``) or a group's counter
    (``next_seq``)."""
    live = core_document["paths"][BALANCED_GROUPS_PATH]["get"]
    for name, document in (
        ("openapi-v1.stable.json", stable_snapshot),
        ("openapi-v1.full.json", full_snapshot),
    ):
        operation = document["paths"][BALANCED_GROUPS_PATH]["get"]
        assert operation.get("x-stability") == "beta", name
        assert operation == live, f"{name}: the balanced-groups route differs"
        assert _referenced_schemas(document, operation) == _referenced_schemas(
            core_document, live
        ), f"{name}: the balanced-groups schemas differ"
    for name, document in (
        ("openapi-v1.stable.json", stable_snapshot),
        ("openapi-v1.full.json", full_snapshot),
        ("the live core document", core_document),
    ):
        text = json.dumps(document)
        for word in ("balance_seed", "balance_seq", "next_seq"):
            assert word not in text, f"{word} found in {name}"
